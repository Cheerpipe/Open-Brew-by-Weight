#!/bin/sh
# Generates the firmware identity header at the requested output path.
#
# Usage: gen_version.sh [board_arch] [hardware_compat] [machine_compat] [output]
#
# board_arch is the OTA compatibility key (n16r8). It is baked into the
# image tag so the controller can refuse a binary built for another board.
# An n16r8 image also needs both profile compatibility IDs. Callers that do not
# produce a flashable image (host tests) omit all three; the resulting
# "unknown" arch never matches a real controller, which is the safe outcome.
set -eu

root=$(CDPATH='' cd -- "$(dirname -- "$0")/.." && pwd)
version_file="$root/VERSION"
output=${4:-$root/src/OpenBrewByWeightVersion.h}

arch=${1:-unknown}
hardware_compat=${2:-unknown}
machine_compat=${3:-unknown}
case "$arch" in
  n16r8)
    if [ "$#" -lt 3 ]; then
      echo "An n16r8 image needs hardware and machine compatibility IDs." >&2
      exit 1
    fi
    ;;
  unknown) ;;
  *)
    echo "Invalid board arch: '$arch' (expected n16r8 or unknown)" >&2
    exit 1
    ;;
esac
for compat in "$hardware_compat" "$machine_compat"; do
  case "$compat" in
    ''|*[!a-z0-9-]*)
      echo "Invalid profile compatibility ID: '$compat'" >&2
      exit 1
      ;;
  esac
  if [ "${#compat}" -gt 63 ]; then
    echo "Profile compatibility ID is longer than 63 characters: '$compat'" >&2
    exit 1
  fi
done

ver=$(tr -d '[:space:]' < "$version_file")
# Exactly MAJOR.MINOR.PATCH without leading zeros (shell arithmetic below
# would read 08 as invalid octal).
if ! printf '%s\n' "$ver" | grep -Eqx '(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)'; then
  echo "Invalid VERSION: '$ver' (expected MAJOR.MINOR.PATCH)" >&2
  exit 1
fi

major=${ver%%.*}
rest=${ver#*.}
minor=${rest%%.*}
patch=${rest#*.}

if [ "$major" -gt 255 ] || [ "$minor" -gt 255 ] || [ "$patch" -gt 65535 ]; then
  echo "Invalid VERSION: '$ver' (major/minor <= 255, patch <= 65535)" >&2
  exit 1
fi

packed=$(( (major << 24) | (minor << 16) | patch ))

if git -C "$root" rev-parse --is-inside-work-tree >/dev/null 2>&1; then
  sha=$(git -C "$root" rev-parse --short=7 HEAD)
  dirty=""
  # Untracked (not ignored) files count too: they can change the image.
  if [ -n "$(git -C "$root" status --porcelain)" ]; then
    dirty="-dirty"
  fi
else
  sha="unknown"
  dirty=""
fi

build_id="${ver}+${sha}${dirty}"
mkdir -p "$(dirname -- "$output")"

cat > "$output.tmp" <<EOF
#pragma once

// Generated by scripts/gen_version.sh — do not edit.

#include <stdint.h>

#define FW_VERSION_STRING "${build_id}"
#define FW_BOARD_ARCH_STRING "${arch}"
#define FW_HARDWARE_COMPAT_STRING "${hardware_compat}"
#define FW_MACHINE_COMPAT_STRING "${machine_compat}"
#define FW_VERSION_PACKED_STRING "${packed}"

// Contiguous marker embedded in every flashable image. The OTA verifier scans
// an uploaded binary for this literal to prove the file is an Open Brew by
// Weight build for this exact board before it may become the boot image. Keep
// the field order and the "|END" terminator in sync with OpenBrewByWeightOta.cpp.
#define FW_IMAGE_TAG_STRING                                     \\
  "OPENBREWBYWEIGHT_FW_TAG_V2|arch=" FW_BOARD_ARCH_STRING       \\
  "|hw=" FW_HARDWARE_COMPAT_STRING                              \\
  "|machine=" FW_MACHINE_COMPAT_STRING                          \\
  "|ver=" FW_VERSION_STRING                                     \\
  "|packed=" FW_VERSION_PACKED_STRING "|END"

namespace openbrewbyweight {

constexpr char FW_VERSION[] = FW_VERSION_STRING;
constexpr char FW_BOARD_ARCH[] = FW_BOARD_ARCH_STRING;
constexpr char FW_HARDWARE_COMPAT[] = FW_HARDWARE_COMPAT_STRING;
constexpr char FW_MACHINE_COMPAT[] = FW_MACHINE_COMPAT_STRING;
constexpr uint32_t FW_VERSION_PACKED = 0x$(printf '%08x' "$packed")U;

}  // namespace openbrewbyweight
EOF

# Rewrite only on change so unchanged builds do not recompile every includer.
if cmp -s "$output.tmp" "$output"; then rm -f "$output.tmp"; else mv "$output.tmp" "$output"; fi
echo "Generated $output ($build_id, arch=$arch, hw=$hardware_compat, machine=$machine_compat)"
